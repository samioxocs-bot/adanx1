function shuffleDeterministic(arr, seed) {
  const copy = [...arr]
  for (let i = copy.length - 1; i > 0; i--) {
    const j = (seed * 31 + i * 17) % (i + 1)
    ;[copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}

function makeChoices(correct, pool, qIndex) {
  const distractors = pool.filter(x => x !== correct)
  const picked = []
  for (let k = 0; k < 3; k++) {
    picked.push(distractors[(qIndex * 7 + k * 5) % distractors.length])
  }
  const all = [correct, ...picked]
  const rotated = shuffleDeterministic(all, qIndex + 11)
  return {
    options: rotated,
    correctIndex: rotated.indexOf(correct)
  }
}

